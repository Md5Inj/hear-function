export function tr(s, locale) {
  if (locale !== 'ru' || s == null || s === '') return s;
  const str = String(s);
  if (RU[str]) return RU[str];
  let m;
  if ((m = str.match(/^Chords: (.*)\. Up to (\d+) bars$/))) return 'Аккорды: ' + m[1] + '. До ' + m[2] + ' тактов';
  if ((m = str.match(/^Chords: (.*)$/))) return 'Аккорды: ' + m[1];
  if ((m = str.match(/^(.+) (major|minor)$/)) && !RU[m[1]]) return m[1] + ' ' + RU[m[2]];
  if (str.includes(' · ')) return str.split(' · ').map(x => tr(x, locale)).join(' · ');
  if ((m = str.match(/^([^:]+): (.+)$/))) return tr(m[1], locale) + ': ' + tr(m[2], locale);
  if (str.includes(', ')) { const parts = str.split(', '); if (parts.every(p => RU[p] || !/[a-z]{3,}/.test(p))) return parts.map(p => RU[p] || p).join(', '); }
  return str;
}

/* уровень с текстами на нужном языке; логика (vocab, semis, degrees…) не меняется */
export function locLevel(l, locale) {
  if (!l || locale !== 'ru') return l;
  return Object.assign({}, l, { title: tr(l.title, locale), desc: tr(l.desc, locale), short: l.short && tr(l.short, locale), group: l.group && tr(l.group, locale) });
}
export const locLevels = (arr, locale) => locale === 'ru' && arr ? arr.map(l => locLevel(l, locale)) : arr;
